function global:tb_welcome($s) {
  Write-Host ("  {0}Welcome to {1}{2}{3}{0}, {4}! Your DevOps toolbox is ready.{3}" -f $global:TB_W, $global:TB_B, $s.Host, $global:TB_R, $s.User)
