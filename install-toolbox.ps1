function global:toolbox-theme {
  param([string]$Name)
  if (-not $Name) {
    Write-Host ''
    $cur = "$env:DEVOPS_TOOLBOX_THEME"; if (-not $global:TB_Themes.Contains($cur)) { $cur = 'ocean' }
    foreach ($t in $global:TB_Themes.Keys) { Write-Host ('  ' + (tb_theme_preview $t -Current:($t -eq $cur))) }
    Write-Host ''
    Write-Host "  current: $cur $([char]0xB7) switch: toolbox-theme <name> (also changes Windows Terminal colours)"
    Write-Host ''
    return
  }
  $Name = $Name.ToLower()
  if (-not $global:TB_Themes.Contains($Name)) { Write-Host "unknown theme '$Name' (choose: $($global:TB_Themes.Keys -join ' '))" -ForegroundColor Yellow; return }
  tb_save_setting 'DEVOPS_TOOLBOX_THEME' $Name
  $env:DEVOPS_TOOLBOX_THEME = $Name
  if ($env:DEVOPS_TOOLBOX_WT -ne '0') { $null = tb_wt_apply $Name }
  tb_banner
}
Register-ArgumentCompleter -CommandName toolbox-theme -ParameterName Name -ScriptBlock {
  param($cmd, $param, $word) $global:TB_Themes.Keys | Where-Object { $_ -like "$word*" }
}

