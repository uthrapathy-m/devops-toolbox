function Test-ExecutionPolicy {
  # Profiles only run when the policy allows local scripts. Returns $true when it does.
  $eff = 'Undefined'
  foreach ($s in 'MachinePolicy', 'UserPolicy', 'CurrentUser', 'LocalMachine') {
    $v = "$(Get-ExecutionPolicy -Scope $s)"; if ($v -ne 'Undefined') { $eff = $v; break }
  }
  if ($eff -eq 'Undefined') { $eff = 'Restricted' }
  if (@('RemoteSigned', 'Unrestricted', 'Bypass') -contains $eff) { return $true }
  Say $G_WARN $YE "PowerShell's execution policy is '$eff', so your profile (and the toolbox) won't load."
  $ok = $Yes
  if (-not $ok -and (Test-CanPrompt)) {
    Write-Host "    Set it to RemoteSigned for your user only? This is the usual setting for developers. [Y/n] " -NoNewline
    $a = [Console]::ReadKey($true); Write-Host ''
    $ok = $a.Key -ne 'N'
  }
  if (-not $ok) { Say $G_SKIP $DIM 'left as is. Later: Set-ExecutionPolicy -Scope CurrentUser RemoteSigned'; return $false }
  if ($DryRun) { Say $G_SKIP $DIM 'would run: Set-ExecutionPolicy -Scope CurrentUser RemoteSigned'; return $true }
  try { Set-ExecutionPolicy -Scope CurrentUser -ExecutionPolicy RemoteSigned -Force; Say $G_OK $GR 'execution policy: RemoteSigned (current user)'; return $true }
  catch { Say $G_WARN $YE "could not change it: $($_.Exception.Message)"; return $false }
}

