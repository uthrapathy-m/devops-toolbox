}
function global:tb_banner([string]$Mode) {
  tb_init; $s = tb_stats
  if ($Mode -eq 'welcome') { Write-Host ''; tb_welcome $s; return }
  $pl = { param($n, $w) if ($n -eq 1) { "$n $w" } else { "$n ${w}s" } }
  $up = '{0}; {1}; {2} min' -f (& $pl $s.UD 'day'), (& $pl $s.UH 'hour'), $s.UM
  Write-Host ''
  tb_logo
  tb_tag ("$([char]0xA9) $((Get-Date).Year) $($s.User)@$($s.Host)")
  tb_rule
  tb_text "System Information: Build: $($s.Build); Uptime: $up; Shell: $($s.Shell)"
  tb_rule
  tb_text "$($s.OS) * $($s.Arch) * $($s.Cpus) CPU"
  tb_text "Memory: $($s.Mem); Disk($($s.DiskName)): $($s.Disk); IP: $($s.IP)"
  if (tb_has kubectl) { $c = $s.Ctx; if (-not $c) { $c = 'none' }; tb_text "K8s: $c" }
  tb_rule
  Write-Host ''
  tb_welcome $s
}

function global:tb_compact_lines {
  # exactly 10 rows: logo (6) + date/tag + rule + 2 live lines, used by the pinned pane
  tb_init; $s = tb_stats; $dot = [string][char]0xB7
  $out = @(); for ($i = 0; $i -lt 6; $i++) { $out += '  ' + (tb_c $global:TB_Stops[$i]) + $global:TB_Logo[$i] + $global:TB_R }
  $when = (Get-Date).ToString('ddd dd MMM yyyy  HH:mm', [Globalization.CultureInfo]::InvariantCulture)
  $tag = "$([char]0xA9) $((Get-Date).Year) $($s.User)@$($s.Host)"
  $pad = 57 - 2 - $when.Length - $tag.Length; if ($pad -lt 2) { $pad = 2 }
  $out += "  $global:TB_P$global:TB_B$when$global:TB_R$(' ' * $pad)$global:TB_D$tag$global:TB_R"
  $out += "  $global:TB_SEP$global:TB_LINE$global:TB_R"
  $out += "  $global:TB_G" + "Build $($s.Build) $dot up $($s.UD)d $($s.UH)h $($s.UM)m $dot $($s.Cpus) CPU $dot $($s.OS)$global:TB_R"
  $ctx = ''; if ($s.Ctx) { $ctx = " $dot $global:TB_P$([char]0x2388) $($s.Ctx)$global:TB_G" }
  $out += "  $global:TB_G" + "Mem $($s.Mem) $dot Disk $($s.Disk) $dot IP $($s.IP)$ctx$global:TB_R"
  $out
}
function global:tb_read_theme {
  # the theme saved in custom.ps1 (the pinned pane re-reads it, so toolbox-theme updates it live)
