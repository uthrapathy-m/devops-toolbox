<#
  DevOps Toolbox for Windows / PowerShell (5.1 and 7).
  The same banner and 7 colour themes as the Linux toolbox, matching Windows Terminal colour
  schemes, CLI tools installed with winget (pick them from a menu) and alias packs.

  One-liner (PowerShell):
    irm https://raw.githubusercontent.com/uthrapathy-m/devops-toolbox/main/install-toolbox.ps1 | iex

  From a downloaded file:
    .\install-toolbox.ps1                                   # menus
    .\install-toolbox.ps1 -Profile k8s -Theme amber -Yes    # no menus
    .\install-toolbox.ps1 -Tools fzf,zoxide,alias-git -Yes  # exact items
    .\install-toolbox.ps1 -List | -Uninstall | -DryRun | -Upgrade
  With the one-liner, preset options with env vars:
    $env:TOOLBOX_PROFILE='core'; $env:TOOLBOX_THEME='ice'; $env:TOOLBOX_YES='1'; irm ... | iex
#>
