  Say $G_OK $GR "removed $TbHome"
  Write-Host ''
  Write-Host "  ${DIM}Tools installed with winget stay installed. Remove one with: winget uninstall --id <id>$R"
  Write-Host "  ${DIM}Open a new terminal to finish.$R"
  Write-Host ''
}

