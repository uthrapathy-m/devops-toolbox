# A 10-row read-only pane above the shell redraws the compact banner every 5 s. It is tied to this
# shell: it closes when the shell exits, and hides while ssh runs (the server has its own banner).
function global:tb_pin_file([string]$Ext) { Join-Path $global:TB_Home "cache\pin-$PID.$Ext" }
function global:tb_pin_active {
  $f = tb_pin_file 'pid'
  if (Test-Path $f) { $p = "$(Get-Content $f -ErrorAction SilentlyContinue)".Trim(); if ($p -and (Get-Process -Id $p -ErrorAction SilentlyContinue)) { return $true } }
  $false
}
function global:tb_pin_show([switch]$Quiet) {
  if (-not $env:WT_SESSION) { if (-not $Quiet) { Write-Host '  The pinned banner needs Windows Terminal.' -ForegroundColor Yellow }; return $false }
  if (tb_pin_active) { return $true }
  $h = 0; $w = 0; try { $h = $Host.UI.RawUI.WindowSize.Height; $w = $Host.UI.RawUI.WindowSize.Width } catch { }
  if ($h -lt 26 -or $w -lt 60) { if (-not $Quiet) { Write-Host "  Window too small for the pinned banner (needs 60x26, this is ${w}x$h)." -ForegroundColor Yellow }; return $false }
  # The new pane opens below and is then swapped to the top. A swap keeps each slot's size, so the
  # new pane gets the big share now and the shell ends up in it; the top slot keeps ~10 rows.
  $size = [math]::Min(0.95, [math]::Max(0.5, [math]::Round(1 - 10.6 / $h, 3))).ToString([Globalization.CultureInfo]::InvariantCulture)
  $pin = Join-Path $global:TB_Home 'pin.ps1'
  if (-not (Test-Path $pin)) { return $false }
  $exe = (Get-Process -Id $PID).Path
  New-Item -ItemType Directory -Force -Path (Join-Path $global:TB_Home 'cache') | Out-Null
  Remove-Item (tb_pin_file 'stop') -ErrorAction SilentlyContinue
  $prof = ''; if ($env:WT_PROFILE_ID) { $prof = "-p `"$env:WT_PROFILE_ID`" " }
  # new pane below (-H), then swap it to the top and give the focus back to this shell
  $a = "-w 0 sp -H -s $size $prof--title devops-toolbox `"$exe`" -NoLogo -NoProfile -ExecutionPolicy Bypass -File `"$pin`" -Watch $PID ; swap-pane up ; move-focus down"
  try { Start-Process -FilePath 'wt.exe' -ArgumentList $a -WindowStyle Hidden; return $true } catch { return $false }
}
function global:tb_pin_hide {
  if (tb_pin_active) { Set-Content -Path (tb_pin_file 'stop') -Value '1' }   # the pane exits cleanly within a second
}
