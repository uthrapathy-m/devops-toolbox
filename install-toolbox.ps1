    $code = Invoke-Winget $it $verb
    if ($code -eq 0) { Say $G_OK $GR ("{0,-16} {1}" -f $it.Name, $(if ($have) { 'up to date' } else { 'installed' })) }
    else { Say $G_X $RD ("{0,-16} failed (winget exit {1}); see {2}" -f $it.Name, $code, (Join-Path $LogDir "$($it.Id).log")); $failed += $it.Name }
  }
}
if ($toInstall -and -not $DryRun) { Update-SessionPath }

# delta as git pager, unless the user already chose one
if ($Sel['delta'] -and -not $DryRun -and (Get-Command git -ErrorAction SilentlyContinue) -and (Get-Command delta -ErrorAction SilentlyContinue)) {
  $pager = (& git config --global --get core.pager) 2>$null
  if (-not $pager) {
    & git config --global core.pager delta; & git config --global interactive.diffFilter 'delta --color-only'
    & git config --global delta.navigate true; & git config --global merge.conflictstyle zdiff3
    Say $G_OK $GR 'git now shows diffs with delta'
  }
}

# 4. shell setup
Write-Host ''
Write-Host "  ${CY}PowerShell setup$R"
$state = @(Get-State) + @($chosen | Where-Object { $_.IsPack } | ForEach-Object Id) | Select-Object -Unique
$packs = @($state | ForEach-Object { $PackName[$_] } | Where-Object { $_ })
$packLine = '$global:TB_Packs = @(' + (($packs | ForEach-Object { "'$_'" }) -join ', ') + ')'
$src = $ModuleSrc.Replace('$global:TB_Packs = @()  # @PACKS@', $packLine)
if ($DryRun) {
  Say $G_SKIP $DIM "would write $ModPath (alias packs: $($packs -join ', '))"
} else {
  New-Item -ItemType Directory -Force -Path $TbHome | Out-Null
  [IO.File]::WriteAllText($ModPath, $src, (New-Object Text.UTF8Encoding $true))
  [IO.File]::WriteAllText((Join-Path $TbHome 'pin.ps1'), $PinSrc, (New-Object Text.UTF8Encoding $true))
  Set-Content -Path $StateFile -Value $state -Encoding UTF8
  $cf = Join-Path $TbHome 'custom.ps1'
  if (-not (Test-Path $cf)) {
    Set-Content -Path $cf -Encoding UTF8 -Value @(
      '# devops-toolbox: your own aliases and settings for PowerShell. The installer never overwrites this file.',
      "# `$env:DEVOPS_TOOLBOX_BANNER = '0'    # 0 = no banner, fastfetch = fastfetch instead",
      "# `$env:DEVOPS_TOOLBOX_PROMPT = '0'    # 0 = keep your own prompt instead of starship",
      "# `$env:DEVOPS_TOOLBOX_WT = '0'        # 0 = toolbox-theme leaves Windows Terminal colours alone",
      "# `$env:DEVOPS_TOOLBOX_PIN = '0'       # 0 = no pinned banner pane (same as: toolbox-pin off)",
      '# function global:proj { Set-Location D:\projects }'
    )
  }
  tb_save_setting 'DEVOPS_TOOLBOX_THEME' $Theme
  if ($NoTerminalScheme) { tb_save_setting 'DEVOPS_TOOLBOX_WT' '0' }
  Remove-Item -Force -ErrorAction SilentlyContinue (Join-Path $TbHome 'cache\kubectl-completion.ps1')
  Say $G_OK $GR "toolbox module  $DIM$ModPath$R"
  Say $G_OK $GR "theme: $Theme  $DIM(alias packs: $($packs -join ', '))$R"
}
$policyOk = Test-ExecutionPolicy
Set-ProfileLine
if ($state -contains 'gitbash') { Install-GitBash $packs }

# 5. Windows Terminal
if ($NoTerminalScheme) {
  Say $G_SKIP $DIM 'Windows Terminal left unchanged (-NoTerminalScheme)'
} elseif (-not (tb_wt_files)) {
  Say $G_SKIP $DIM 'Windows Terminal not found; the banner works in any terminal with 24-bit colour'
} elseif ($DryRun) {
  Say $G_SKIP $DIM "would add 7 'DevOps Toolbox' colour schemes to Windows Terminal and select '$(tb_title $Theme)'"
