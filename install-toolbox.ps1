function Select-One([string]$Title, [string]$Hint, [string[]]$Lines, [int]$Index = 0) {
  # Lines are pre-rendered option strings; returns the chosen index, or -1 for quit.
  while ($true) {
    Clear-Screen; Show-Logo
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine(''); [void]$sb.AppendLine("  $CY$BO$Title$R"); [void]$sb.AppendLine("  $DIM$Hint$R"); [void]$sb.AppendLine('')
    for ($i = 0; $i -lt $Lines.Count; $i++) {
      if ($i -eq $Index) { [void]$sb.AppendLine("  $CY$G_PTR$R $BO$($Lines[$i])$R") } else { [void]$sb.AppendLine("    $($Lines[$i])") }
    }
    [Console]::Write($sb.ToString())
    $k = [Console]::ReadKey($true)
    switch ($k.Key) {
      'UpArrow' { $Index = ($Index - 1 + $Lines.Count) % $Lines.Count }
      'DownArrow' { $Index = ($Index + 1) % $Lines.Count }
      'K' { $Index = ($Index - 1 + $Lines.Count) % $Lines.Count }
      'J' { $Index = ($Index + 1) % $Lines.Count }
      'Enter' { return $Index }
      'Escape' { return -1 }
      'Q' { return -1 }
      default { $n = [int]$k.KeyChar - [int][char]'1'; if ($n -ge 0 -and $n -lt $Lines.Count) { return $n } }
    }
  }
}

function Select-Items([hashtable]$Sel) {
  # Checklist grouped by category. Space toggles, a = all, n = none, Enter = continue.
  $rows = @(); foreach ($c in $CatTitle.Keys) { $rows += [pscustomobject]@{ Head = $CatTitle[$c] }; foreach ($it in $Catalog | Where-Object { $_.Cat -eq $c }) { $rows += $it } }
  $items = @($rows | Where-Object { -not $_.Head })
  $inst = @{}; foreach ($it in $items) { $inst[$it.Id] = Test-Installed $it }
  $cur = 0
  while ($true) {
    $h = Get-WindowHeight; $view = [Math]::Max(8, $h - 8)
    $curRow = [array]::IndexOf($rows, $items[$cur])
    $top = [Math]::Max(0, [Math]::Min($curRow - [int]($view / 2), $rows.Count - $view))
    $n = @($items | Where-Object { $Sel[$_.Id] }).Count
    $sb = New-Object Text.StringBuilder
    [void]$sb.AppendLine("  $CY${BO}Pick what to install$R  $DIM($n selected)$R")
    [void]$sb.AppendLine("  $DIM" + "Up/Down move $G_DOT Space toggle $G_DOT a all $G_DOT n none $G_DOT Enter continue $G_DOT q quit$R")
    for ($r = $top; $r -lt [Math]::Min($rows.Count, $top + $view); $r++) {
      $row = $rows[$r]
      if ($row.Head) { [void]$sb.AppendLine(''); [void]$sb.AppendLine("  $CY$($row.Head)$R"); continue }
      $on = $Sel[$row.Id]; $box = "$DIM$G_OFF$R"; if ($on) { $box = "$GR$G_ON$R" }
      $tag = ''; if ($inst[$row.Id]) { $tag = " $DIM(installed)$R" }
      $ptr = '  '; $nm = $row.Name; if ($row -eq $items[$cur]) { $ptr = "$CY$G_PTR$R "; $nm = "$BO$nm$R" }
      [void]$sb.AppendLine(('  {0}{1} {2}{3} {4}{5}{6}' -f $ptr, $box, $nm, (' ' * [Math]::Max(1, 18 - $row.Name.Length)), $DIM, $row.Desc, $R) + $tag)
    }
    Clear-Screen; [Console]::Write($sb.ToString())
    $k = [Console]::ReadKey($true)
    switch ($k.Key) {
      'UpArrow' { $cur = ($cur - 1 + $items.Count) % $items.Count }
      'DownArrow' { $cur = ($cur + 1) % $items.Count }
      'K' { $cur = ($cur - 1 + $items.Count) % $items.Count }
      'J' { $cur = ($cur + 1) % $items.Count }
      'PageUp' { $cur = [Math]::Max(0, $cur - 10) }
      'PageDown' { $cur = [Math]::Min($items.Count - 1, $cur + 10) }
      'Spacebar' { $Sel[$items[$cur].Id] = -not $Sel[$items[$cur].Id] }
      'A' { foreach ($it in $items) { if ($it.Id -ne 'docker') { $Sel[$it.Id] = $true } } }
      'N' { foreach ($it in $items) { $Sel[$it.Id] = $false } }
      'Enter' { return $true }
      'Escape' { return $false }
      'Q' { return $false }
    }
  }
}

function Invoke-Winget($it, [string]$verb) {
  New-Item -ItemType Directory -Force -Path $LogDir | Out-Null
  $log = Join-Path $LogDir "$($it.Id).log"
  $codeAll = 0
  foreach ($wid in $it.Winget) {
    $a = @($verb, '--id', $wid, '-e', '--source', 'winget', '--accept-package-agreements', '--accept-source-agreements', '--disable-interactivity', '--silent')
    $p = Start-Process -FilePath 'winget' -ArgumentList $a -NoNewWindow -PassThru -RedirectStandardOutput $log -RedirectStandardError "$log.err"
    $null = $p.Handle
    $i = 0
    while (-not $p.HasExited) {
      [Console]::Write("`r  $CY$($Spin[$i % $Spin.Count])$R $verb $($it.Name) $DIM($wid)$R ")
      Start-Sleep -Milliseconds 120; $i++
    }
    $p.WaitForExit()
    $code = $p.ExitCode
    # 0 ok, 3010 ok (restart needed), 0x8A15002B no newer version, 0x8A150061 already installed
    if (@(0, 3010, -1978335189, -1978335135) -notcontains $code) { $codeAll = $code }
  }
  [Console]::Write("`r$E[2K")
  $codeAll
}

