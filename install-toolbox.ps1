  $n = tb_wt_apply $Theme
  if ($n) { Say $G_OK $GR "Windows Terminal: 7 colour schemes added, default is 'DevOps Toolbox $(tb_title $Theme)'  ${DIM}(backup: settings.json.toolbox-backup)$R" }
  if ($state -contains 'gitbash') { Set-GitBashColours }
}

