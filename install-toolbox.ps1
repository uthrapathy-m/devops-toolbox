function global:tb_stats {
  $inv = [Globalization.CultureInfo]::InvariantCulture
  $s = @{ User = $env:USERNAME; Host = $env:COMPUTERNAME; Cpus = [Environment]::ProcessorCount; Arch = $env:PROCESSOR_ARCHITECTURE }
  $s.Shell = 'PowerShell {0}.{1}' -f $PSVersionTable.PSVersion.Major, $PSVersionTable.PSVersion.Minor
  try {
    $r = Get-ItemProperty 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion' -ErrorAction Stop
    $name = "$($r.ProductName)"; if ([int]$r.CurrentBuild -ge 22000) { $name = $name -replace 'Windows 10', 'Windows 11' }
    $s.OS = ("$name $($r.DisplayVersion)").Trim(); $s.Build = "$($r.CurrentBuild).$($r.UBR)"
  } catch { $s.OS = 'Windows'; $s.Build = [Environment]::OSVersion.Version.ToString() }
  if ($PSVersionTable.PSVersion.Major -ge 6) { $ms = [Environment]::TickCount64 } else { $ms = ([long][Environment]::TickCount + 4294967296) % 4294967296 }
  $up = [TimeSpan]::FromMilliseconds($ms); $s.UD = $up.Days; $s.UH = $up.Hours; $s.UM = $up.Minutes
  try {
    Add-Type -AssemblyName Microsoft.VisualBasic -ErrorAction Stop
    $ci = New-Object Microsoft.VisualBasic.Devices.ComputerInfo
    $tot = [double]$ci.TotalPhysicalMemory; $avail = [double]$ci.AvailablePhysicalMemory
  } catch {
    $o = Get-CimInstance Win32_OperatingSystem -Property TotalVisibleMemorySize, FreePhysicalMemory
    $tot = [double]$o.TotalVisibleMemorySize * 1KB; $avail = [double]$o.FreePhysicalMemory * 1KB
  }
  $s.Mem = '{0}G/{1}G' -f (($tot - $avail) / 1GB).ToString('0.0', $inv), ($tot / 1GB).ToString('0.0', $inv)
  try {
    $d = New-Object IO.DriveInfo $env:SystemDrive
    $used = $d.TotalSize - $d.TotalFreeSpace
    $s.DiskName = $env:SystemDrive; $s.Disk = '{0}G/{1}G ({2}%)' -f [math]::Round($used / 1GB), [math]::Round($d.TotalSize / 1GB), [math]::Round(100 * $used / $d.TotalSize)
  } catch { $s.DiskName = 'C:'; $s.Disk = '?' }
  $s.IP = '?'
  try {
    foreach ($n in [Net.NetworkInformation.NetworkInterface]::GetAllNetworkInterfaces()) {
      if ($n.OperationalStatus -ne 'Up' -or $n.NetworkInterfaceType -eq 'Loopback' -or $n.NetworkInterfaceType -eq 'Tunnel') { continue }
      $p = $n.GetIPProperties()
      if (-not ($p.GatewayAddresses | Where-Object { $_.Address.AddressFamily -eq 'InterNetwork' })) { continue }
      $a = $p.UnicastAddresses | Where-Object { $_.Address.AddressFamily -eq 'InterNetwork' } | Select-Object -First 1
      if ($a) { $s.IP = $a.Address.ToString(); break }
    }
  } catch { }
  $kc = "$env:KUBECONFIG".Split(';')[0]; if (-not $kc -or -not (Test-Path $kc)) { $kc = Join-Path $HOME '.kube\config' }
  $s.Ctx = ''
  if (Test-Path $kc) {
    $m = Select-String -Path $kc -Pattern '^current-context:\s*"?([^"\s]+)' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($m) { $s.Ctx = $m.Matches[0].Groups[1].Value }
  }
  $s
}

